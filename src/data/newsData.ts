export const getNewsByCategory = (category: NewsCategory): NewsArticle[] => {
  if (category === 'Все') {
    return newsArticles;
  }
  return newsArticles.filter(article => article.category === category);
};

export const getNewsById = (id: string): NewsArticle | undefined => {
  return newsArticles.find(article => article.id === id);
};

export const getLatestNews = (count: number = 4): NewsArticle[] => {
  return [...newsArticles].sort((a, b) => {
    return new Date(b.date).getTime() - new Date(a.date).getTime();
  }).slice(0, count);
};
